/**
 * Shortest importer path from an entry to `id`, as project-relative names. Undefined when no
 * entry reaches `id`: modules loaded only to be inspected (the CommonJS check loads `.js`
 * files the analyzer resolves) are not in the bundle.
 */
function importChain(
  context: Rollup.PluginContext,
  id: string,
  root: string
): string[] | undefined {
  const label = (module: string) =>
    SERVER_ONLY_MARKERS.includes(module)
      ? 'state-surface/server-only'
      : module.startsWith('\0')
        ? module.slice(1)
        : path.isAbsolute(module)
          ? path.relative(root, module).split(path.sep).join('/')
          : module;
  const previous = new Map<string, string | undefined>([[id, undefined]]);
  const queue = [id];
  let entry: string | undefined;
  while (queue.length && !entry) {
    const current = queue.shift()!;
    const info = context.getModuleInfo(current);
    const importers = [...(info?.importers ?? []), ...(info?.dynamicImporters ?? [])];
    if (info?.isEntry) entry = current;
    for (const importer of importers)
      if (!previous.has(importer)) {
        previous.set(importer, current);
        queue.push(importer);
      }
  }
  if (!entry) return undefined;
  const chain: string[] = [];
  for (let at: string | undefined = entry; at; at = previous.get(at)) chain.push(label(at));
  // Start at the island/plugin module: loader → islands map is engine plumbing.
  const start = chain.findIndex(name => name === ISLANDS || name === PLUGINS);
  return start >= 0 && start < chain.length - 1 ? chain.slice(start + 1) : chain;
}

/** Rollup prefixes hook errors with the plugin name; drop ours to avoid printing it twice. */
function forRollup(error: unknown): never {
  if (error instanceof SurfaceBuildError)
    error.message = error.message.replace(/^\[state-surface\] /, '');
  throw error;
}

type Resolver = (source: string, importer: string) => Promise<string | undefined>;

/**
 * Server-only imports reachable from browser modules (islands, client slots, plugins, the
 * app entry), found without a client build: the same rule the build reports in buildEnd.
 */
async function browserLeaks(
  root: string,
  roots: string[],
  analyzer: SurfaceAnalyzer,
  resolve: Resolver
) {
  const { builtinModules } = await import('node:module');
  const builtins = new Set(builtinModules);
  const errors: SurfaceBuildError[] = [];
  const previous = new Map<string, string | undefined>(roots.map(file => [file, undefined]));
  const queue = [...new Set(roots)];
  const label = (file: string) => path.relative(root, file).split(path.sep).join('/');
  while (queue.length) {
    const file = queue.shift()!;
    const module = await analyzer.module(file).catch(() => undefined);
    for (const source of module?.sources ?? []) {
      const target = await resolve(source, file);
      const leak =
        source === 'state-surface/server-only' ||
        source.startsWith('node:') ||
        builtins.has(source) ||
        (!!target && /\.server\.[cm]?[jt]sx?$/.test(target));
      if (leak) {
        const chain: string[] = [];
        for (let at: string | undefined = file; at; at = previous.get(at)) chain.unshift(label(at));
        errors.push(
          new SurfaceBuildError(
            `"${source}" is server-only and is reachable from the browser bundle: ${[...chain, target && source !== 'state-surface/server-only' ? label(target) : source].join(' → ')}`,
            {
              ...(await importSite(file, source)),
              hint: 'Move the server code behind a server Slot (defineServerComponent) or a transition, or pass the data as public props.',
            }
          )
        );
        continue;
      }
      if (analyzer.isProjectFile(target) && !previous.has(target)) {
        previous.set(target, file);
        queue.push(target);
      }
    }
  }
  return errors;
}

const escapeRegExp = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/** Import specifiers that resolve to the server-only module `id`. */
function importPattern(id: string): RegExp {
  const file = id.split('?')[0];
  if (SERVER_ONLY_MARKERS.includes(file)) return /['"]state-surface\/server-only['"]/;
  const builtin = file.replace(/^__vite-browser-external:/, '').replace(/^node:/, '');
  if (builtin !== file) return new RegExp(`['"](?:node:)?${escapeRegExp(builtin)}['"]`);
  const base = path.basename(file).replace(/\.[cm]?[jt]sx?$/, '');
  return new RegExp(`['"][^'"]*\\b${escapeRegExp(base)}(?:\\.[cm]?[jt]sx?)?['"]`);
}

/** The line importing `source` (a specifier or pattern) in `file`, for a located diagnostic. */
async function importSite(file: string, source: string | RegExp) {
  const code = await readFile(file, 'utf8').catch(() => undefined);
  if (code === undefined) return { file };
  const pattern =
    typeof source === 'string' ? new RegExp(`['"]${escapeRegExp(source)}['"]`) : source;
  const index = code.search(pattern);
  if (index < 0) return { file, code, offset: 0 };
  const start = code.lastIndexOf('\n', index) + 1;
  return { file, code, offset: start + (code.slice(start).match(/^\s*/)?.[0].length ?? 0) };
}
