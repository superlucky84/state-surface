import path from 'node:path';
import { listFiles } from './fsUtils.js';
import { SurfaceBuildError, atDefaultExport } from './diagnostics.js';
import { TRANSITION_NAME } from '../server/transition.js';

export interface ScannedTransition {
  /** Path under `transitions/` without extension, `/`-separated (DC-16 ③). */
  name: string;
  filePath: string;
}

const EXTENSIONS = /\.(?:ts|mts|js|mjs)$/;

/**
 * Transitions are `transitions/**\/*.ts`; the relative path is the name (`comment/add`).
 * Files and folders starting with `_` are helpers, tests and declarations are skipped.
 * Names are kebab-case segments because they appear in URLs and `data-action`.
 */
export async function scanTransitions(dir: string): Promise<ScannedTransition[]> {
  const owners = new Map<string, string>();
  const transitions: ScannedTransition[] = [];
  for (const file of (await listFiles(dir)).sort()) {
    const relative = path.relative(dir, file).split(path.sep).join('/');
    if (!EXTENSIONS.test(relative) || /\.d\.[mc]?ts$/.test(relative)) continue;
    if (/\.(test|spec)\.[mc]?[jt]s$/.test(relative)) continue;
    if (relative.split('/').some(segment => segment.startsWith('_'))) continue;
    const name = relative.replace(EXTENSIONS, '');
    if (!TRANSITION_NAME.test(name))
      throw new SurfaceBuildError(
        `Transition file transitions/${relative} has an invalid name "${name}".`,
        {
          file,
          hint: 'Use kebab-case file and folder names (transitions/comment/add-reply.ts → "comment/add-reply"); put helpers in _-prefixed files.',
        }
      );
    const previous = owners.get(name);
    if (previous)
      throw new SurfaceBuildError(
        `transitions/${previous} and transitions/${relative} both register "${name}".`,
        {
          ...(await atDefaultExport(file)),
          hint: 'Transition names are file paths under transitions/; rename or remove one file.',
        }
      );
    owners.set(name, relative);
    transitions.push({ name, filePath: file });
  }
  return transitions;
}

/**
 * `.state-surface/actions.d.ts` (DC-22 ⑤): transition name → params type for `useAction` and
 * `<Boot>`. Type-only imports, so handler code never reaches the client (V-05).
 */
export function actionTypes(root: string, transitions: ScannedTransition[]): string {
  const outDir = path.join(root, '.state-surface');
  const lines = transitions.map(transition => {
    const target = path
      .relative(outDir, transition.filePath)
      .split(path.sep)
      .join('/')
      .replace(EXTENSIONS, '');
    return `      ${JSON.stringify(transition.name)}: ParamsOf<typeof import(${JSON.stringify(target)}).default>;`;
  });
  return [
    '// Generated by state-surface from transitions/**. Do not edit.',
    "import type { ParamsOf } from 'state-surface/server';",
    '',
    'declare global {',
    '  namespace StateSurface {',
    '    interface Actions {',
    ...lines,
    '    }',
    '  }',
    '}',
    '',
    'export {};',
    '',
  ].join('\n');
}
